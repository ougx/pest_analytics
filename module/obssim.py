@callback(
    Output(name+"plot", "figure"),
    Input( name+"update-plot", "n_clicks"),
    State( "pest-data", "data"),
    State( name+"nobs", "value"),
    State( name+"iter", "value"),
    State( name+"highr", "value"),
    State( name+"palette", "value"),
    State( name+"invcmap", "checked"),
    State( name+"norm", "checked"),
)
def plot(clicks, data, nobs, iiter, highr, palette, invcmap, normalized):
    if clicks is None or clicks == 0:
        return px.scatter(title="Upload data and click 'Plot Similarity' to see plot")
    if data is None or data == {}:
        return px.scatter(title="No data uploaded. Please upload data and click 'Plot Similarity' to see plot")
    pst, par, obs, pars, reis, jcos = parse_zip(data, False, False, True)
    if obs is None:
        return px.scatter(title="No .pst file found in zip file.")
    if not jcos:
        return px.scatter(title="No .jco file found in zip file.")

    jco0 = jcos[int(iiter)]
    mask = jco0.index.isin(obs.obsname)
    So = get_obssim(obs, jco0)
    d = np.sqrt(np.diag(So))
    Sc = So / np.outer(d, d)
    ScOff = (Sc - np.identity(len(Sc))).abs()
    rmax = ScOff.max().dropna().sort_values()
    mask = So.index.isin(rmax.index[-int(nobs):])

    SS = Sc.loc[mask, mask] if normalized else So.loc[mask, mask]
    # print(SS)
    fig = px.imshow(
        SS,
        color_continuous_scale=palette + ('_r' if invcmap else ""),
        aspect='equal',
        width=900,
        height=750,
        # text_auto=True
    )

    ScOff = ScOff.loc[mask, mask]
    highcor = ScOff[ScOff>float(highr)].stack().dropna().reset_index()
    # print(highcor)
    if len(highcor):
        par1 = highcor.iloc[:, 0].tolist() + highcor.iloc[:, 1].tolist()
        par2 = highcor.iloc[:, 1].tolist() + highcor.iloc[:, 0].tolist()
        rr = pd.Series(highcor.iloc[:, 2].tolist() + highcor.iloc[:, 2].tolist())
        fig.add_trace(go.Scatter(
            x=par1,
            y=par2,
            text= rr.to_string(header=False, index=False).split("\n"),
            mode="markers",
            marker=dict(size=8, symbol="circle", color="white"),
            showlegend=False,
        ))
    fig.update_layout(
        xaxis=dict(tickangle=90),
        coloraxis=dict(cmin=-1, cmax=1,colorbar=dict(
            x=0.93,
            title=dict(text="Observation Similarity", side="right"),
        ))
    )
    fig.update_yaxes(autorange="reversed")
    return fig
