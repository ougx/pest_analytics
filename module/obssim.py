md = dcc.Markdown('''

    The observation similarity matrix is similar to the parameter correlation matrix but it describes relationships between observations instead of parameters.

    The observation similarity matrix $S$ is also calculated using the Jacobian matrix:
    $$
                   S = (JQJ^T),
    $$
    where $J$ is the Jacobian matrix; and Q is the weighting matrix. Therefore, this analysis also requires the `.jco` files generated by PEST.

    The diagonal elements represent observation sensitivity (strength, L2 norm) while off-diagonal elements represent observation redundancy (similar information).
    High observation similarity means that the observation pair responds to parameters in almost the same way. In another word, they provide duplicated information
    Unlike high parameter correlation, however, this does not mean that they need to be removed unless removing such observations can for computational efficiency.
    If such observations are clustered together, you can down weight them or use representative value per cluster.
    ''',
    mathjax=True)


