@callback(
    Output(name+"iter", "data"),
    Input( "pest-data", "data"),
)
def upload_pest(data):
    if data is None or data == {}:
        return no_update
    contents = data.get("contents")
    filename = data.get("filename")
    pst, par, obs, pars, reis, jcos = parse_zip(contents, False, False, True)
    if jcos is {}:
        return no_update
    else:
        return [str(i) for i in jcos.keys()]


@callback(
    Output(name+"plot", "figure"),
    Input( name+"update-plot", "n_clicks"),
    State( "pest-data", "data"),
    State( name+"npar", "value"),
    State( name+"iter", "value"),
    State( name+"highr", "value"),
    State( name+"palette", "value"),
    State( name+"invcmap", "checked"),
)
def plot(clicks, data, npar, iiter, highr, palette, invcmap):
    if clicks is None or clicks == 0:
        return px.scatter(title="Upload data and click 'Plot Correlation' to see plot")
    if data is None or data == {}:
        return px.scatter(title="No data uploaded. Please upload data and click 'Plot Correlation' to see plot")
    contents = data.get("contents")
    filename = data.get("filename")
    pst, par, obs, pars, reis, jcos = parse_zip(contents, False, False, True)
    if obs is None:
        return px.scatter(title="No .pst file found in zip file.")
    if jcos is {}:
        return px.scatter(title="No .jco file found in zip file.")

    csplimit = 1e-10
    nobs_useful = (obs.weight > 0).sum()

    jco0 = jcos[int(iiter)]
    mask = jco0.index.isin(obs.obsname)
    jco = jco0.loc[mask, ]
    WJ = jco * obs.set_index("obsname").loc[jco.index, "weight"].values[:, None]
    csp = (WJ**2).sum() ** 0.5 / nobs_useful
    mask = WJ.columns.isin(csp[csp>csplimit].index)
    JJ = WJ.loc[:,mask]
    J2 = np.matmul(JJ.T, JJ)
    try:
        cov = np.linalg.inv(J2)
    except:
        cov = np.linalg.pinv(J2)
    std = np.sqrt(np.diag(cov))
    cor = cov / np.outer(std, std)
    cor = pd.DataFrame(cor, index=J2.columns, columns=J2.columns)

    rmax = (cor - np.identity(len(cor))).abs().max().dropna().sort_values()
    mask = cor.index.isin(rmax.index[-int(npar):])
    cor = cor.loc[mask, mask]
    fig = px.imshow(
        cor,
        color_continuous_scale=palette + ('_r' if invcmap else ""),
        aspect='equal',
        width=900,
        height=750,
        # text_auto=True
    )

    cor_off = cor - np.identity(len(cor))
    highcor = cor_off[cor_off.abs()>float(highr)].stack().dropna().reset_index()
    if len(highcor):
        par1 = highcor.iloc[:, 0].tolist() + highcor.iloc[:, 1].tolist()
        par2 = highcor.iloc[:, 1].tolist() + highcor.iloc[:, 0].tolist()
        rr = pd.Series(highcor.iloc[:, 2].tolist() + highcor.iloc[:, 2].tolist())
        fig.add_trace(go.Scatter(
            x=par1,
            y=par2,
            text= rr.to_string(header=False, index=False).split("\n"),
            mode="markers",
            marker=dict(size=8, symbol="circle", color="white"),
            showlegend=False,
        ))
    fig.update_layout(
        xaxis=dict(tickangle=90),
        coloraxis=dict(cmin=-1, cmax=1,colorbar=dict(
            x=0.93,
            title=dict(text="Parameter Correlation", side="right"),
        ))
    )
    fig.update_yaxes(autorange="reversed")
    return fig
