@callback(
    Output(name+"parselect", "data"),
    Output(name+"grp"   , "data"),
    Output(name+"grp"   , "value"),
    Input ("pest-data", "data"),
)
def upload_pest(data):
    if data is None or data == {}:
        return no_update
    pst, par, obs, pars, reis, jcos = parse_zip(data, False, False, False)
    if par is None:
        return [no_update, no_update, no_update]
    else:
        pp = par[par.partrans.isin(["log", "none"])]
        dats = []
        for gp, df in pp.groupby("pargrp"):
            dats.append({"group": gp, "items": df.parname.tolist()})
    # print(obs, update_groups(data, "obsgrp"))
    return [dats] + update_groups(data, "obsgrp")

@callback(
    Output(name+"plot", "figure"),
    Input( name+"update-plot", "n_clicks"),
    State( "pest-data", "data"),
    State( name+"stype", "value"),
    State( name+"otype", "value"),
    State( name+"grp", "value"),
    State(name+"nobs", "value"),
    State(name+"palette", "value"),
    State(name+"parselect", "value"),
)
def plot(clicks, data, stype, otype, grp, nobs, palette, parselect):
    if clicks is None or clicks == 0:
        return px.scatter(title="Upload data and click 'Plot Sensitivity' to see plot")
    if data is None or data == {}:
        return px.scatter(title="No data uploaded. Please upload data and click 'Plot Sensitivity' to see plot")
    pst, par, obs, pars, reis, jcos = parse_zip(data, True, True, True)
    if par is None:
        return px.scatter(title="No .pst file found in zip")
    if not pars:
        return px.scatter(title="No .par file found in zip")
    if not jcos:
        return px.scatter(title="No .jco file found in zip")
    if not reis:
        return px.scatter(title="No .rei file found in zip")
    if not parselect:
        return px.scatter(title="No parameter is selected.")
    if not isiterable(parselect):
        parselect = [parselect]

    ddf = {} # aggregated sensitivity
    sdf = {} # (raw)signed sensitivity
    for i, df0 in jcos.items():
        df = pd.merge(df0, obs, left_index=True, right_on="obsname", suffixes=(None, "_1"))
        df.set_index("obsname", inplace=True)
        sdf[f"Iter {i}"] = (df["weight"].values[:, None] * df[parselect]).sum(axis=1)
        if stype == "L1 Norm":
            ddf[f"Iter {i}"] =  (df["weight"].values[:, None] * df[parselect] .abs()).sum(axis=1)
        else:
            ddf[f"Iter {i}"] = ((df["weight"].values[:, None] * df[parselect])**2).sum(axis=1)
    sdf = pd.DataFrame(sdf, )
    ddf = pd.DataFrame(ddf, )
    if otype == "Obs Groups":
        ddf = ddf.groupby(obs.set_index("obsname").loc[ddf.index, grp]).sum()
        sdf = sdf.groupby(obs.set_index("obsname").loc[sdf.index, grp]).sum()

    if stype == "L2 Norm":
        ddf = ddf**0.5

    tot = (ddf / ddf.max(axis=0).values[None,:]).sum(axis=1)
    tot = tot.sort_values(ascending=False).iloc[:int(nobs)]
    ddf = ddf.loc[tot.index]
    sdf = sdf.loc[tot.index]
    sdf = pd.DataFrame(np.where(sdf>0, "triangle-up", "triangle-down"), columns=ddf.columns)

    pp = {"Iter 0": par.set_index("parname").loc[parselect, "parval0"]}
    for i, df in pars.items():
        pp[f"Iter {i}"] = df.set_index("parname").loc[parselect, "parval"]

    ddf["Iter 0"] = 0
    sdf["Iter 0"] = "circle"

    colors = px.colors.sample_colorscale(palettes[palette], ddf.shape[1])

    fig = make_subplots(
        rows=1, cols=2, column_widths=[1, 0.1*len(parselect)],
        subplot_titles=("Parameter Sensitivity", "Parameter Values")
    )

    # add parameter update plot
    for (i, df),c in zip(pp.items(), colors):
        fig.add_trace(go.Scatter(
            x=parselect,
            y=df.values,
            mode="markers",
            name=i,
            marker=dict(color=c),
            showlegend=False,
        ), row=1, col=2)

    # add sensitivity plot
    for i, c in enumerate(ddf.sort_index(axis=1).columns):
        if otype=="Observations":
            res = reis[i].set_index("obsname").loc[ddf.index]
            res["val"] = res["modelled"] #* obs.set_index("name").loc[ddf.index]
        fig.add_trace(go.Scatter(
            x=ddf.index,
            # x=obs.set_index("obsname").loc[ddf.index, ["obsval"]].to_string(index=True, header=False).split("\n"),
            y=ddf[c],
            text=None if otype!="Observations" else res["val"].to_string(index=False, header=False).split("\n"),
            mode="lines+markers",
            name=c,
            hovertemplate='Sen:%{y}; Modeled:%{text}',
            line=dict(color=colors[i]),
            marker=dict(size=10, symbol=sdf[c])
        ))
    fig.update_layout(
        hovermode="x unified",
        xaxis=dict(
            tickangle=90,
            unifiedhovertitle=dict(
                text='<b>%{x}</b>',
            )
        ),
    )
    # fig.update_layout(
    #     xaxis=dict(title=otype, tickangle=90),
    #     yaxis=dict(title="Parameter Sensitivity"),
    #     row=1, col=1,
    # )
    # fig.update_layout(
    #     xaxis=dict(title="Parameter", tickangle=90),
    #     row=1, col=2,
    # )

    return fig
