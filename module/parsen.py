@callback(
    Output(name+"parselect", "data"),
    Output(name+"grp"   , "data"),
    Output(name+"grp"   , "value"),
    Input ("pest-data", "data"),
)
def fill_lists(data):
    if data is None or data == {}:
        return no_update
    pst, par, obs, pars, reis, jcos = parse_zip(data, False, False, False)
    if par is None:
        return [no_update, no_update, no_update]
    else:
        pp = par[par.partrans.isin(["log", "none"])]
        dats = []
        for gp, df in pp.groupby("pargrp"):
            dats.append({"group": gp, "items": df.parname.tolist()})
    # print(obs, update_groups(data, "obsgrp"))
    return [dats] + update_groups(data, "obsgrp")

@callback(
    Output(name+"weight", "data"),
    Output(name+"weight", "value"),
    Input( "pest-data", "data"),
)
def upload_weight_columns(data):
    return update_weights(data, "weight")


@callback(
    Output(name+"plot", "figure"),
    Input( name+"update-plot", "n_clicks"),
    State( "pest-data", "data"),
    State( name+"stype", "value"),
    State( name+"otype", "value"),
    State( name+"grp", "value"),
    State(name+"nobs", "value"),
    State(name+"palette", "value"),
    State(name+"parselect", "value"),
    State( name+"weight", "value"),
)
def plot(clicks, data, stype, otype, grp, nobs, palette, parselect, weight="weight"):
    if clicks is None or clicks == 0:
        return message_figure("Load data, then click 'Plot Sensitivity'.")
    if data is None or data == {}:
        return message_figure("No data loaded. Load data on the Upload Data page, then click 'Plot Sensitivity'.")
    pst, par, obs, pars, reis, jcos = parse_zip(data, True, True, True)
    if par is None:
        return message_figure("No .pst file found in zip")
    if not pars:
        return message_figure("No .par file found in zip")
    if not jcos:
        return message_figure("No .jco file found in zip")
    if not reis:
        return message_figure("No .rei file found in zip")
    if not parselect:
        return message_figure("No parameter is selected.")
    if not isiterable(parselect):
        parselect = [parselect]

    ddf, sdf = jacobian_sensitivity(jcos, obs, stype, weight, parameters=parselect)
    if otype == "Obs Groups":
        ddf = ddf.groupby(obs.set_index("obsname").loc[ddf.index, grp]).sum()
        sdf = sdf.groupby(obs.set_index("obsname").loc[sdf.index, grp]).sum()
    ddf, sdf = rank_sensitivity(ddf, sdf, stype, nobs)

    pp = {"Iter 0": par.set_index("parname").loc[parselect, "parval0"]}
    for i, df in sorted(pars.items()):
        pp[f"Iter {i}"] = df.set_index("parname").loc[parselect, "parval"]

    # Jacobian k is computed at the parameters of iteration k-1, so it gets that iteration's color
    colors = px.colors.sample_colorscale(palettes[palette], len(pp))
    par_color = dict(zip(pp, colors))

    fig = make_subplots(
        rows=1, cols=2, column_widths=[1, 0.1*len(parselect)],
        subplot_titles=("Sensitivity by Jacobian (colored by the iteration it was computed at)", "Parameter Values")
    )

    # add parameter update plot
    for (i, df),c in zip(pp.items(), colors):
        fig.add_trace(go.Scatter(
            x=parselect,
            y=df.values,
            mode="markers",
            name=i,
            marker=dict(color=c),
            showlegend=False,
        ), row=1, col=2)

    # add sensitivity plot
    for c in sorted(ddf.columns, key=lambda c: int(c.split()[1])):
        k = int(c.split()[1])
        text = None
        rei = get_jco_rei(reis, k)
        if otype=="Observations" and rei is not None:
            text = rei.set_index("obsname").loc[ddf.index, "modelled"].to_string(index=False, header=False).split("\n")
        fig.add_trace(go.Scatter(
            x=ddf.index,
            # x=obs.set_index("obsname").loc[ddf.index, ["obsval"]].to_string(index=True, header=False).split("\n"),
            y=ddf[c],
            text=text,
            mode="lines+markers",
            name=c,
            hovertemplate='Sen:%{y}; Modeled:%{text}',
            line=dict(color=par_color.get(f"Iter {k-1}", colors[-1])),
            marker=dict(size=10, symbol=sdf[c])
        ))
    fig.update_layout(
        hovermode="x unified",
        xaxis=dict(
            tickangle=90,
            unifiedhovertitle=dict(
                text='<b>%{x}</b>',
            )
        ),
    )
    # fig.update_layout(
    #     xaxis=dict(title=otype, tickangle=90),
    #     yaxis=dict(title="Parameter Sensitivity"),
    #     row=1, col=1,
    # )
    # fig.update_layout(
    #     xaxis=dict(title="Parameter", tickangle=90),
    #     row=1, col=2,
    # )

    return fig
