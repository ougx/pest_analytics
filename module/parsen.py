@callback(
    Output(name+"parselect", "data"),
    Input ("pest-data", "data"),
)
def upload_pest(data):
    if data is None or data == {}:
        return no_update
    contents = data.get("contents")
    filename = data.get("filename")
    pst, par, obs, pars, reis, jcos = parse_zip(contents, False, False, False)
    if par is None:
        return no_update
    else:
        pp = par[par.partrans.isin(["log", "none"])]
        data = []
        for gp, df in pp.groupby("pargp"):
            data.append({"group": gp, "items": df.parname.tolist()})
    return data

@callback(
    Output(name+"plot", "figure"),
    Input( name+"update-plot", "n_clicks"),
    State( "pest-data", "data"),
    State( name+"stype", "value"),
    State( name+"otype", "value"),
    State(name+"nobs", "value"),
    State(name+"palette", "value"),
    State(name+"parselect", "value"),
)
def plot(clicks, data, stype, otype, nobs, palette, parselect):
    if clicks is None or clicks == 0:
        return px.scatter(title="Upload data and click 'Plot Parameter' to see plot")
    if data is None or data == {}:
        return no_update
    contents = data.get("contents")
    filename = data.get("filename")
    pst, par, obs, pars, reis, jcos = parse_zip(contents, True, True, True)
    if par is None:
        return no_update
    if not parselect:
        return no_update
    if not isiterable(parselect):
        parselect = [parselect]

    ddf = {} # aggregated sensitivity
    sdf = {} # (raw)signed sensitivity
    for i, df0 in jcos.items():
        df = pd.merge(df0, obs, left_index=True, right_on="obsname")
        df.set_index("obsname", inplace=True)
        sdf[f"Iter {i}"] = (df["weight"].values[:, None] * df[parselect]).sum(axis=1)
        if stype == "L1 Norm":
            ddf[f"Iter {i}"] =  (df["weight"].values[:, None] * df[parselect] .abs()).sum(axis=1)
        else:
            ddf[f"Iter {i}"] = ((df["weight"].values[:, None] * df[parselect])**2).sum(axis=1)
    sdf = pd.DataFrame(sdf, )
    ddf = pd.DataFrame(ddf, )
    if otype == "Obs Groups":
        ddf = ddf.groupby(obs.set_index("obsname").loc[ddf.index, "obsgp"]).sum()

    if stype == "L2 Norm":
        ddf = ddf**0.5

    tot = (ddf / ddf.max(axis=0).values[None,:]).sum(axis=1)
    tot = tot.sort_values(ascending=False).iloc[:int(nobs)]
    ddf = ddf.loc[tot.index]
    sdf = sdf.loc[tot.index]
    sdf = pd.DataFrame(np.where(sdf>0, "triangle-up", "triangle-down"), columns=ddf.columns)

    pp = {"Iter 0": par.set_index("parname").loc[parselect, "parval0"]}
    for i, df in pars.items():
        pp[f"Iter {i}"] = df.set_index("parname").loc[parselect, "parval"]

    ddf["Iter 0"] = 0
    sdf["Iter 0"] = "circle"

    colors = px.colors.sample_colorscale(palettes[palette], ddf.shape[1])

    fig = make_subplots(
        rows=1, cols=2, column_widths=[1, 0.1*len(parselect)],
        subplot_titles=("Parameter Sensitivity", "Parameter Values")
    )

    # add parameter update plot
    for (i, df),c in zip(pp.items(), colors):
        fig.add_trace(go.Scatter(
            x=parselect,
            y=df.values,
            mode="markers",
            name=i,
            marker=dict(color=c),
            showlegend=False,
        ), row=1, col=2)

    # add sensitivity plot
    for i, c in enumerate(ddf.sort_index(axis=1).columns):
        fig.add_trace(go.Scatter(
            x=ddf.index,
            y=ddf[c],
            text=reis[i].set_index("name").loc[ddf.index, "modelled"].to_string(index=False, header=False).split("\n"),
            mode="lines+markers",
            name=c,
            hovertemplate='Sen:%{y}; Modeled:%{text}',
            line=dict(color=colors[i]),
            marker=dict(size=10, symbol=sdf[c])
        ))
    fig.update_layout(
        hovermode="x unified",
        xaxis=dict(tickangle=90)
    )
    # fig.update_layout(
    #     xaxis=dict(title=otype, tickangle=90),
    #     yaxis=dict(title="Parameter Sensitivity"),
    #     row=1, col=1,
    # )
    # fig.update_layout(
    #     xaxis=dict(title="Parameter", tickangle=90),
    #     row=1, col=2,
    # )

    return fig
